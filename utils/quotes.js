/**
 * 鼓励语 —— 各页顶上那行小字。
 *
 * 三条约定：
 *
 * 一、**不是随机抽，是循环**。先洗出一份随机顺序，再一句一句往下走，走完重新洗牌
 *     从头来。随机抽的毛病是「怎么老是这句」—— 真随机本来就会连着重复，看着像 bug；
 *     循环则保证一整轮里每句都露一次面，而每轮的先后次序又是打乱的，
 *     不至于每次打开都按同一个顺序背下来。
 *
 * 二、**顺序是所有页面共用的**。序列和游标都放在模块级：小程序里同一个模块只实例化
 *     一次，各页 require 到的是同一份，于是「切一次页 = 翻一句」，主页看到的和
 *     「我的」看到的不会撞车。**不落盘**：这不是用户数据，存下来只是多一份要迁移的
 *     东西，重启小程序重新洗牌就够了。
 *
 * 三、**只出文本，不出样式**。字号 / 颜色 / 截断都由页面决定：这行字是配角，
 *     各个页面的头部高度和留白都不一样，样式交给页面才压得住，不至于喧宾夺主。
 */

