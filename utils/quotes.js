/** 本轮的出句顺序（QUOTES 的下标，已洗乱）与下一个要出的位置 */
let _order = []
let _cursor = 0

/** 洗牌：0..n-1 的一个随机排列（Fisher–Yates） */
function shuffle() {
  const idx = QUOTES.map((q, i) => i)
  for (let i = idx.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1))
    const t = idx[i]
    idx[i] = idx[j]
    idx[j] = t
  }
  return idx
}

/**
 * 取下一句。一轮走完自动重新洗牌接着来，所以永远取得到。
 *
 * 游标只进不出，页面拿不到「这是第几句」—— 进度不往外露，
 * 页面也就不必操心一轮到头的边界。
 * @returns {{text:String, author:String}}
 */
function next() {
  if (_cursor >= _order.length) {
    _order = shuffle()
    _cursor = 0
  }
  const q = QUOTES[_order[_cursor]]
  _cursor++
  return { text: q.text, author: q.author }
}

