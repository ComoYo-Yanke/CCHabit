/**
 * 抽一句。
 *
 * 刻意**不排除上一句**：连着两次抽到同一句的概率是 1/32，
 * 为这点概率塞一个「记住上次抽了啥」的状态，两个页面各自维护还容易不同步，
 * 不划算 —— 而且真连上了也就一句小字，不至于看成 bug。
 * @returns {{text:String, author:String}}
 */
function pick() {
  return QUOTES[Math.floor(Math.random() * QUOTES.length)]
}

