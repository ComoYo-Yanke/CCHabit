/**
 * 鼓励语 —— 主页和「我的」顶上那行小字。
 *
 * 两条约定：
 *
 * 一、**每叫一次抽一句，不缓存**。缓存过一版（同一个进程里只抽一次），
 *     结果是「切回主页还是那句」；改成不缓存之后，每次切到这两个页面都会换一句，
 *     两页之间也就自然不一样了。调用方是页面的 onShow（不是 onLoad），
 *     所以「切回来」才算一次，页内重绘不会把句子抽走。
 *
 * 二、**只出文本，不出样式**。字号 / 颜色 / 截断都由页面决定：这行字是配角，
 *     各个页面的头部高度和留白都不一样，样式交给页面才压得住，不至于喧宾夺主。
 *
 * 名字很直白（pick 而不是 randomQuote）：调用方只有页面那两处，
 * 一眼看得懂比省几个字符有用。
 */

