/**
 * 取某个版本的更新条目。
 * 认不出这个版本（老数据、或日志里还没补上）时返回空数组，
 * 调用方不必先查表 —— 首页的更新弹窗靠它决定列什么。
 */
function changelogOf(version) {
  const hit = CHANGELOG.filter((c) => c.version === version)[0]
  return hit ? hit.items : []
}

module.exports = {
  APP_VERSION,
  CHANGELOG,
  changelogOf
}
